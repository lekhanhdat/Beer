// Chỉ dùng origin kiểm thử riêng; dữ liệu được xóa sau khi hoàn thành.
async (page) => {
  const checks = [], errors = [];
  page.on('pageerror', e => errors.push(e.message));
  const check = (ok, name) => { if (!ok) throw new Error(name); checks.push(name); };
  const read = () => page.evaluate(() => JSON.parse(localStorage.getItem('kho-bia.data.v1')));
  const seed = { version: 1, products: [{ id: 'tiger', name: 'Tiger', initialStock: 1, initialDate: '2026-10-01', active: true }], transactions: [{ id: 'prior', date: '2026-10-31', type: 'in', items: [{ productId: 'tiger', quantity: 2 }], note: 'Tháng trước' }, { id: 'current', date: '2026-11-01', type: 'in', items: [{ productId: 'tiger', quantity: 1 }], note: 'Đầu tháng' }] };
  await page.goto('http://127.0.0.1:8765');
  await page.evaluate(data => { localStorage.clear(); localStorage.setItem('kho-bia.data.v1', JSON.stringify(data)); }, seed); await page.reload();
  check((await page.locator('#total-stock').textContent()).trim() === '4 thùng', 'Dữ liệu cũ tự đọc được, tồn không bị nhân lại');
  check((await page.locator('#monthly-in').textContent()).trim() === '1 thùng', 'Card nhập trong tháng loại bỏ tồn đầu kỳ và tháng trước');
  await page.locator('[data-type=out]').click();
  await page.locator('#transaction-date').fill('2026-11-12');
  await page.locator('#transaction-operator').fill('Nhân viên Minh');
  await page.locator('.item-product').selectOption('tiger');
  await page.locator('.item-unit').selectOption('can');
  await page.locator('.item-quantity').fill('10');
  check((await page.locator('#editor-total').textContent()) === '10 lon', 'Phiếu xuất chọn lon và tổng đúng 10 lon');
  await page.locator('#transaction-operator').fill('   ');
  await page.locator('#save-transaction').click();
  check((await page.locator('#transaction-error').textContent()).includes('tên người thực hiện'), 'Không lưu tên nhân viên chỉ có khoảng trắng');
  await page.locator('#transaction-operator').fill('Nhân viên Minh');
  await page.locator('#save-transaction').click();
  const saved = await read();
  check(saved.version === 2 && saved.transactions[0].items[0].unit === 'case', 'Lần lưu đầu nâng v1 sang v2 mà giữ phiếu cũ theo thùng');
  const looseId = saved.transactions.find(t => t.type === 'out').id;
  check(saved.transactions.find(t => t.id === looseId).operator === 'Nhân viên Minh', 'Lưu tên người thực hiện nhập xuất');
  check((await page.locator('#total-stock').textContent()).trim() === '3 thùng 14 lon', 'Xuất 10 lon còn 3 thùng 14 lon');
  check((await page.locator('#monthly-out').textContent()).trim() === '10 lon', 'Card xuất tháng tính được lon lẻ');
  await page.reload();
  check((await page.locator('#total-stock').textContent()).trim() === '3 thùng 14 lon', 'Tồn lon lẻ giữ chính xác khi tải lại');
  await page.locator('[data-page=history]').click();
  await page.locator('[data-edit-transaction="' + looseId + '"]').click();
  check(await page.locator('.item-unit').inputValue() === 'can' && await page.locator('.item-quantity').inputValue() === '10', 'Mở sửa giữ đơn vị lon và số lượng');
  check(await page.locator('#transaction-operator').inputValue() === 'Nhân viên Minh', 'Mở sửa giữ tên nhân viên');
  await page.locator('.item-quantity').fill('11'); await page.locator('#save-transaction').click();
  check((await page.locator('#total-stock').textContent()).trim() === '3 thùng 13 lon', 'Sửa phiếu lon cập nhật tồn chính xác');
  await page.locator('#open-review').click();
  await page.locator('#review-from').fill('2026-11-11');
  await page.locator('#review-to').fill('2026-11-12'); await page.locator('#review-to').dispatchEvent('change');
  await page.locator('#reviewer-name').fill('Quản lý Hương');
  check((await page.locator('#review-preview').textContent()).includes('Nhân viên Minh'), 'Quản lý xem được nhân viên và số lượng trước khi xác nhận');
  await page.locator('#save-review').click();
  check(!await page.locator('#review-dialog').isVisible() && (await read()).reviews.length === 1, 'Xác nhận gộp hai ngày và lưu mốc');
  await page.reload(); await page.locator('[data-page=history]').click();
  check((await page.locator('#history-list').textContent()).includes('Quản lý Hương'), 'Lịch sử hiển thị quản lý xác nhận sau tải lại');
  await page.locator('[data-edit-transaction="' + looseId + '"]').click();
  await page.locator('#transaction-note').fill('Bổ sung ghi chú sau xác nhận'); await page.locator('#save-transaction').click();
  await page.locator('.review-details summary').click();
  check((await page.locator('#review-list').textContent()).includes('Cần xem lại'), 'Sửa phiếu sau xác nhận đánh dấu cần xem lại');
  await page.locator('[data-page=history]').click();
  const row = page.locator('#history-list tbody tr').filter({ hasText: 'Nhân viên Minh' });
  check((await row.textContent()).includes('Chưa xác nhận'), 'Phiếu đã sửa không còn được đánh dấu đã xác nhận');
  await page.locator('[data-page=overview]').click(); await page.locator('#open-review').click();
  await page.locator('#review-from').fill('2026-11-11'); await page.locator('#review-to').fill('2026-11-12'); await page.locator('#review-to').dispatchEvent('change');
  await page.locator('#save-review').click();
  check((await read()).reviews.length === 2, 'Có thể xác nhận lại, giữ mốc cũ');

  // Phiếu thay đổi lúc quản lý đang xem không được xác nhận bằng danh sách cũ.
  await page.locator('#open-review').click();
  await page.locator('#review-from').fill('2026-11-11'); await page.locator('#review-to').fill('2026-11-12'); await page.locator('#review-to').dispatchEvent('change');
  const other = await page.context().newPage(); await other.goto('http://127.0.0.1:8765');
  await other.locator('[data-page=history]').click(); await other.locator('[data-edit-transaction="' + looseId + '"]').click();
  await other.locator('.item-quantity').fill('12'); await other.locator('#save-transaction').click();
  await page.locator('#total-stock').filter({ hasText: '12 lon' }).waitFor();
  await page.locator('#save-review').click();
  check((await page.locator('#review-error').textContent()).includes('Phiếu đã thay đổi'), 'Chặn xác nhận bằng dữ liệu cũ khi tab khác sửa phiếu');
  check((await read()).reviews.length === 2, 'Xung đột không ghi mốc xác nhận');
  await page.locator('#save-review').click();
  check((await read()).reviews.length === 3, 'Xem dữ liệu mới rồi xác nhận được');
  await other.close();
  await page.locator('#open-review').click();
  await page.locator('#review-to').fill('2099-12-31'); await page.locator('#review-to').dispatchEvent('change');
  check(await page.locator('#save-review').isDisabled(), 'Không xác nhận trước ngày tương lai');
  await page.locator('#review-dialog [data-close]').first().click();
  await page.locator('[data-page=backup]').click();
  const pendingDownload = page.waitForEvent('download');
  await page.locator('#export-json').click();
  const download = await pendingDownload;
  const stream = await download.createReadStream();
  const chunks = []; for await (const chunk of stream) chunks.push(chunk);
  const backup = JSON.parse(Buffer.concat(chunks).toString('utf8'));
  check(backup.version === 2 && backup.reviews.length === 3 && backup.transactions.find(t => t.id === looseId).items[0].unit === 'can', 'File JSON chứa đủ đơn vị lon và các mốc xác nhận');
  await page.locator('#import-file').setInputFiles({ name: 'v2-backup.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(backup)) });
  check((await page.locator('#confirm-copy').textContent()).includes('3 mốc xác nhận'), 'Tóm tắt khôi phục hiển thị số mốc xác nhận');
  await page.locator('#confirm-action').click();
  check((await read()).reviews.length === 3 && (await read()).transactions.find(t => t.id === looseId).operator === 'Nhân viên Minh', 'Khôi phục JSON v2 giữ tên nhân viên và mốc quản lý');
  await page.locator('[data-page=overview]').click();
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.locator('#toast').waitFor({ state: 'hidden' });
  await page.screenshot({ path: 'output/playwright/features-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth), 'Home mới không tràn ngang ở 390px');
  await page.screenshot({ path: 'output/playwright/features-mobile.png', fullPage: true });
  await page.locator('#open-review').click();
  check(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth), 'Cửa sổ xác nhận không tràn ngang trên điện thoại');
  await page.locator('#review-dialog [data-close]').first().click();
  await page.setViewportSize({ width: 320, height: 740 });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth), 'Home mới không tràn ngang ở 320px');
  check(errors.length === 0, 'Không có lỗi JavaScript: ' + errors.join('; '));
  await page.evaluate(() => localStorage.clear()); await page.reload();
  return { passed: checks.length, checks };
}
