// Chạy bằng Playwright CLI: run-code --filename tests/browser-qa.js
// Chỉ dùng trên origin kiểm thử riêng: bài kiểm thử xóa dữ liệu tại origin đó.
async (page) => {
  const checks = [];
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const check = (condition, name) => { if (!condition) throw new Error(name); checks.push(name); };
  const read = () => page.evaluate(() => JSON.parse(localStorage.getItem('kho-bia.data.v1')));
  const content = id => page.locator('#' + id).textContent();
  const go = name => page.locator('[data-page="' + name + '"]').click();
  const confirm = () => page.locator('#confirm-action').click();
  const addProduct = async (name, initial = 0) => {
    await go('catalog'); await page.locator('#add-product').click();
    await page.locator('#product-name').fill(name);
    await page.locator('#product-initial').fill(String(initial));
    await page.locator('#product-date').fill('2026-11-01');
    await page.locator('#product-form button[type=submit]').click();
    check(!await page.locator('#product-dialog').isVisible(), 'Lưu loại bia: ' + name);
  };
  const start = async (type, date, items, note = '') => {
    await go('overview');
    await page.locator('[data-new-type="' + type + '"]').first().click();
    if (await page.locator('#confirm-dialog').isVisible()) await confirm();
    await page.locator('#transaction-date').fill(date);
    await page.locator('#transaction-operator').fill('Minh');
    for (let n = 0; n < items.length; n++) {
      if (n) await page.locator('#add-item').click();
      await page.locator('.item-product').nth(n).selectOption({ label: items[n][0] });
      await page.locator('.item-quantity').nth(n).fill(String(items[n][1]));
    }
    await page.locator('#transaction-note').fill(note);
  };
  const save = () => page.locator('#save-transaction').click();
  const importedFile = data => ({ name: 'kho-bia-qa.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(data)) });
  const downloadText = async button => {
    const pending = page.waitForEvent('download');
    await button.click();
    const download = await pending;
    const stream = await download.createReadStream();
    const chunks = []; for await (const chunk of stream) chunks.push(chunk);
    return Buffer.concat(chunks).toString('utf8');
  };
  await page.goto('http://127.0.0.1:8765');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.evaluate(() => localStorage.clear());
  await page.reload();
  check((await content('total-stock')).trim() === '0 thùng', 'Kho mới bắt đầu bằng 0');
  await addProduct('Tiger'); await addProduct('Heineken', 3);
  await start('in', '2026-11-12', [['Tiger', 10]], 'Nhập bổ sung'); await save();
  check((await read()).transactions.length === 1, 'Lưu phiếu nhập');
  await start('out', '2026-11-13', [['Tiger', 5], ['Heineken', 3]], 'Xuất 2 loại'); await save();
  check((await read()).transactions[1].items.length === 2, 'Một phiếu xuất nhiều loại bia');
  await start('in', '2026-11-15', [['Tiger', 14]], 'Đợt hai'); await save();
  check((await content('total-stock')).trim() === '19 thùng', 'Ví dụ Tiger còn đúng 19 thùng');
  await page.locator('#snapshot-date').fill('2026-11-12');
  await page.locator('#snapshot-date').dispatchEvent('change');
  check((await content('total-stock')).trim() === '13 thùng', 'Tồn quá khứ có cả tồn Heineken đầu kỳ');
  await page.locator('#snapshot-date').fill('2026-11-13');
  await page.locator('#snapshot-date').dispatchEvent('change');
  check((await content('monthly-out')).trim() === '8 thùng', 'Xuất lũy kế tháng đến ngày chọn đúng 8 thùng');
  check((await content('total-stock')).trim() === '5 thùng', 'Tồn ngày 13 đúng 5 thùng');
  await page.reload();
  check((await content('total-stock')).trim() === '19 thùng', 'LocalStorage giữ dữ liệu sau tải lại');
  await start('out', '2026-11-16', [['Tiger', 20]]); await save();
  check((await content('transaction-error')).includes('thiếu 1'), 'Chặn xuất vượt tồn trên giao diện');
  check((await read()).transactions.length === 3, 'Phiếu lỗi không được ghi một phần');
  await page.locator('#transaction-date').fill('2026-11-11');
  await page.locator('.item-quantity').fill('1'); await save();
  check((await content('transaction-error')).includes('2026-11-11'), 'Chặn xuất lùi ngày trước phiếu nhập');
  await start('in', '2026-11-15', [['Tiger', 1], ['Tiger', 2]]); await save();
  check((await content('transaction-error')).includes('bị trùng'), 'Chặn loại bia trùng trong một phiếu');
  await go('history');
  const initial = await read();
  const firstIn = initial.transactions.find(t => t.date === '2026-11-12');
  const out = initial.transactions.find(t => t.type === 'out');
  await page.locator('[data-delete-transaction="' + firstIn.id + '"]').first().click(); await confirm();
  check(await page.locator('#confirm-error').isVisible(), 'Chặn xóa phiếu nhập làm âm tồn ngày sau');
  await page.locator('#confirm-dialog [data-close]').first().click();
  await page.locator('[data-edit-transaction="' + out.id + '"]').first().click();
  if (await page.locator('#confirm-dialog').isVisible()) await confirm();
  await page.locator('.item-quantity').first().fill('4'); await save();
  check((await content('total-stock')).trim() === '20 thùng', 'Sửa phiếu xuất tính lại tồn');
  await go('history');
  await page.locator('#filter-from').fill('2026-11-13');
  await page.locator('#filter-to').fill('2026-11-13');
  await page.locator('#filter-product').selectOption({ label: 'Tiger' });
  await page.locator('#filter-type').selectOption('out');
  check(await page.locator('#history-list tbody tr').count() === 1, 'Lọc kết hợp ngày, loại bia, hình thức');
  const csv = await downloadText(page.locator('#history-csv'));
  check(csv.startsWith('\uFEFF') && csv.includes('"Tiger","0","4"') && !csv.includes('Heineken'), 'CSV UTF-8 đúng dòng đang lọc');
  await page.locator('#history-filters button[type=reset]').click();
  await page.locator('#filter-product').selectOption('');
  await page.locator('#filter-type').selectOption('');
  await page.locator('[data-delete-transaction="' + out.id + '"]').first().click(); await confirm();
  check((await read()).transactions.length === 2, 'Xóa toàn bộ phiếu nhiều dòng');
  await go('overview');
  check((await content('total-stock')).trim() === '27 thùng', 'Xóa xuất trả lại tồn cả hai loại bia');
  await go('catalog');
  const tigerId = (await read()).products.find(p => p.name === 'Tiger').id;
  await page.locator('[data-toggle-product="' + tigerId + '"]').click();
  check((await read()).products.find(p => p.id === tigerId).active === false, 'Ngừng sử dụng loại bia');
  await go('overview');
  check((await content('total-stock')).trim() === '27 thùng', 'Ngừng dùng vẫn giữ tồn và lịch sử');
  check(!await page.locator('.item-product').first().locator('option').allTextContents().then(values => values.includes('Tiger')), 'Loại ngừng dùng không xuất hiện ở phiếu mới');
  await go('catalog'); await page.locator('[data-toggle-product="' + tigerId + '"]').click();
  await page.locator('[data-edit-product="' + tigerId + '"]').click();
  await page.locator('#product-name').fill('Tiger Crystal');
  await page.locator('#product-form button[type=submit]').click();
  check((await read()).products.find(p => p.id === tigerId).name === 'Tiger Crystal', 'Đổi tên vẫn giữ liên kết giao dịch');
  await go('backup');
  const backupText = await downloadText(page.locator('#export-json'));
  const backup = JSON.parse(backupText);
  check(backup.products.length === 2 && backup.transactions.length === 2, 'Xuất JSON đầy đủ danh mục và giao dịch');
  const bad = { ...backup, version: 99 };
  await page.locator('#import-file').setInputFiles(importedFile(bad));
  check(!await page.locator('#confirm-dialog').isVisible() && (await read()).transactions.length === 2, 'Từ chối JSON sai phiên bản mà giữ dữ liệu');
  await addProduct('Bia thử nghiệm');
  await go('backup');
  await page.locator('#import-file').setInputFiles(importedFile(backup));
  check(await page.locator('#confirm-dialog').isVisible(), 'Khôi phục có bản tóm tắt và xác nhận');
  await confirm();
  check((await read()).products.length === 2, 'Khôi phục JSON thay thế chính xác dữ liệu');
  await go('overview');
  check((await content('total-stock')).trim() === '27 thùng', 'Số tồn đúng sau khôi phục JSON');
  await page.locator('#toast').waitFor({ state: 'hidden' });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: 'output/playwright/mobile.png', fullPage: true });
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Điện thoại không tràn ngang');
  await go('history');
  check(await page.locator('#history-list table').isVisible(), 'Lịch sử sử dụng được trên điện thoại');
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Bảng lịch sử cuộn bên trong, không tràn trang');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await go('overview');
  await page.screenshot({ path: 'output/playwright/desktop.png', fullPage: true });

  // Mô phỏng hết bộ nhớ: dữ liệu và nội dung đang nhập phải được giữ lại.
  await start('in', '2026-11-16', [['Tiger Crystal', 2]], 'Chưa lưu do hết bộ nhớ');
  await page.evaluate(() => { window.originalSetItem = Storage.prototype.setItem; Storage.prototype.setItem = function() { throw new DOMException('Quota exceeded', 'QuotaExceededError'); }; });
  await save();
  check((await content('transaction-error')).includes('Không lưu được'), 'Thông báo chính xác khi LocalStorage ghi thất bại');
  check((await read()).transactions.length === 2 && await page.locator('#transaction-note').inputValue() === 'Chưa lưu do hết bộ nhớ', 'Không mất phiếu nháp khi ghi thất bại');
  await page.evaluate(() => { Storage.prototype.setItem = window.originalSetItem; });
  await save();
  check((await read()).transactions.length === 3, 'Có thể lưu lại khi bộ nhớ hoạt động');
  // Dữ liệu lỗi phải khóa ghi và không tự xóa bản gốc.
  const good = await read();
  await page.evaluate(() => localStorage.setItem('kho-bia.data.v1', '{broken'));
  await page.reload();
  check(await page.locator('#storage-warning').isVisible() && await page.locator('#save-transaction').isDisabled(), 'Dữ liệu hỏng khóa thao tác ghi');
  check(await page.evaluate(() => localStorage.getItem('kho-bia.data.v1')) === '{broken', 'Giữ nguyên dữ liệu gốc khi hỏng');
  await go('backup'); await page.locator('#import-file').setInputFiles(importedFile(good)); await confirm();
  check((await read()).transactions.length === 3 && !await page.locator('#storage-warning').isVisible(), 'Khôi phục JSON sửa được dữ liệu lưu bị hỏng');
  check(errors.length === 0, 'Không có lỗi JavaScript: ' + errors.join('; '));
  // Dọn dữ liệu kiểm thử; phiên bàn giao bắt đầu bằng kho trống.
  await page.evaluate(() => localStorage.clear()); await page.reload();
  return { passed: checks.length, checks };
}
